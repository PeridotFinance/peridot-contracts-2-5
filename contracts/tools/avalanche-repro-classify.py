#!/usr/bin/env python3
"""Classify the outcome of one reproduction attempt so a wrapper retries ONLY positively identified transient infrastructure failures.

usage: avalanche-repro-classify.py <exit_code> <path> [<path> ...]      (a path is a log file or an attempt directory scanned for *.txt/*.log)

Prints `CLASS: reason` and exits with a code per class:
  PASS        0   exit code 0 and no failure evidence in the logs
  TRANSIENT  10   exit code != 0, there is at least one failure, and EVERY failure is a positively identified RPC infrastructure error
                  (HTTP 429 / Cloudflare 1015 rate limit, "Max retries exceeded", RPC `database error`, connection reset/timeout, 5xx gateway)
  ASSERTION  20   at least one failing test / failed check whose failure text is NOT an infrastructure error (never retried)
  INCOMPLETE 30   evidence incomplete without a transient cause (NOT-RUN scenarios, missing test outputs, conflicting records, missing
                  aggregate variants, "MATRIX INCOMPLETE"): never retried
  UNKNOWN    40   non-zero exit with no identified cause (compile error, usage error, empty log, crash): never retried

Precedence: ASSERTION > INCOMPLETE > UNKNOWN > TRANSIENT > PASS. A single non-transient failure among transient ones stops the run.
"""
import os
import re
import sys

TRANSIENT = [
    r"HTTP error 429", r"error code: 1015", r"\b429\b.*(too many|rate)", r"Max retries exceeded", r"database error",
    r"failed to get (storage|account|code|balance|nonce|block)", r"connection (reset|refused|closed)", r"(request|operation|connection) timed out",
    r"HTTP error 50[234]", r"Bad Gateway", r"Service Unavailable", r"Gateway Time-?out",
]
TRANSIENT_RE = re.compile("|".join(TRANSIENT), re.I)
FAIL_LINE = re.compile(r"^\s*\[FAIL")   # forge test failure lines only; runner/gate summary lines (`FAILED: ...`) are aggregates, not causes
INCOMPLETE_RE = re.compile(
    r"MATRIX INCOMPLETE|EVIDENCE INCOMPLETE|INCOMPLETE EVIDENCE|NOT-RUN|conflicting-record|missing a mandatory variant|"
    r"manifest test outputs missing: [1-9]|aggregate groups missing a required variant: [1-9]", re.I)
SUITE_FAILED = re.compile(r"Suite result: FAILED|tests? failed|[1-9][0-9]* failing tests?", re.I)
GATE_FAILED_LINE = re.compile(r"^(GATE RUN FAILED OR INCOMPLETE|FAILED: .*)$")


def read_inputs(paths):
    texts = []
    for p in paths:
        if os.path.isdir(p):
            for root, _, files in os.walk(p):
                for f in sorted(files):
                    if f.endswith((".txt", ".log")):
                        texts.append((os.path.join(root, f), open(os.path.join(root, f), errors="replace").read()))
        elif os.path.exists(p):
            texts.append((p, open(p, errors="replace").read()))
    return texts


def classify(exit_code, texts):
    fail_lines, other_fail = [], []
    incomplete = []
    for name, t in texts:
        for ln in t.splitlines():
            s = ln.strip()
            if FAIL_LINE.match(ln):
                (fail_lines if TRANSIENT_RE.search(ln) else other_fail).append((name, s[:200]))
            elif INCOMPLETE_RE.search(s) and not s.startswith(("Verdict counts", "| ", "Generated by")):
                # report-table rows and prose that merely mention these words are not completion failures; only status lines count
                if re.search(r"^(Manifest scenarios:|MATRIX INCOMPLETE|INCOMPLETE EVIDENCE|\*\*EVIDENCE INCOMPLETE)", s):
                    if re.search(r"NOT-RUN: [1-9]|conflicting records: [1-9]|incomplete fallback scenarios: [1-9]|outputs missing: [1-9]|variant: [1-9]|INCOMPLETE", s):
                        incomplete.append((name, s[:200]))
                elif s.startswith(("MATRIX INCOMPLETE", "INCOMPLETE EVIDENCE")):
                    incomplete.append((name, s[:200]))
    # A `[FAIL ...]` line with a non-transient cause is an assertion/real failure.
    if other_fail:
        return "ASSERTION", f"{len(other_fail)} failing test(s) with a non-infrastructure cause, first: {other_fail[0][1]}"
    if exit_code == 0 and not fail_lines and not incomplete:
        return "PASS", "exit 0, no failures"
    if incomplete and not fail_lines:
        return "INCOMPLETE", f"evidence incomplete without a transient cause: {incomplete[0][1]}"
    if fail_lines:
        # Transient only if the incompleteness (if any) is explained by the transient failures (they are the only failures).
        return "TRANSIENT", f"{len(fail_lines)} failure(s), all RPC infrastructure errors, first: {fail_lines[0][1][:120]}"
    if exit_code != 0:
        txt = "\n".join(t for _, t in texts)
        if not txt.strip():
            return "UNKNOWN", f"exit {exit_code} with an empty log"
        return "UNKNOWN", f"exit {exit_code} with no identified failure (compile/usage/crash?)"
    return "PASS", "exit 0"


def main(argv):
    if len(argv) < 3:
        sys.stderr.write(__doc__)
        return 2
    code = int(argv[1])
    cls, why = classify(code, read_inputs(argv[2:]))
    print(f"{cls}: {why}")
    return {"PASS": 0, "TRANSIENT": 10, "ASSERTION": 20, "INCOMPLETE": 30, "UNKNOWN": 40}[cls]


if __name__ == "__main__":
    sys.exit(main(sys.argv))
