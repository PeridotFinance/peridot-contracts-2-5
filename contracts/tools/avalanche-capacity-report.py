#!/usr/bin/env python3
"""Summarise AvalancheCapacityMatrixFork.t.sol forge output into markdown tables.

usage: avalanche-capacity-report.py out1.txt [out2.txt ...] > report.md
Line formats (see the test header): MX| scenario rows, OX| ordinary-lending rows, SG|/SG2| swap-guard rows.
"""
import sys, collections

def money(c):
    return f"{int(c)/100:,.0f}"

mx, ox, sg, opn = [], [], [], []
for f in sys.argv[1:]:
    lines = open(f, errors="replace").read().splitlines()
    pending = None
    for ln in lines:
        ln = ln.strip()
        if ln.startswith("MX|") and ln.endswith("|END"):
            p = ln.split("|")
            mx.append(dict(slice=p[1], cfg=p[2], side=p[3], margin=int(p[4]), k=int(p[5]), path=int(p[6]), lag=int(p[7]),
                           rem=int(p[8]), step=int(p[9]), target=int(p[10]), pool=int(p[11]), oracle=int(p[12]),
                           liq=p[13] == "1", ok=p[14] == "1", rev=p[15], repay=int(p[16]), seized=int(p[17]),
                           reward=int(p[18]), surplus=int(p[19]), ins=int(p[20]), resid=int(p[21]),
                           cost=int(p[22]), exec=int(p[23]), gas=int(p[24])))
        elif ln.startswith("MXOPEN|") and ln.endswith("|END"):
            p = ln.split("|")
            opn.append(dict(slice=p[1], cfg=p[2], side=p[3], margin=int(p[4]), k=int(p[5]), opened=int(p[6]), rev=p[7]))
        elif ln.startswith("OX|") and ln.endswith("|END"):
            p = ln.split("|")
            ox.append(dict(dir=p[1], util=int(p[2]), n=int(p[3]), step=int(p[4]), target=int(p[5]), short=int(p[6]),
                           repay=int(p[7]), seized=int(p[8]), proto=int(p[9]), resid=int(p[10]), bad=int(p[11])))
        elif ln.startswith("SG|"):
            pending = ln.split("|")
        elif ln.startswith("SG2|") and pending:
            q = ln.split("|")
            sg.append((pending, q))
            pending = None

out = []
out.append("# Avalanche capacity matrix (generated)\n")
out.append("Generated by `contracts/tools/avalanche-capacity-report.py` from forge output. Amounts in USD. Evidence classes: "
           "`oracle-only` = MOCKED oracle, pool untouched; `pool-follows` / `lag*` = pool moved by REAL swaps; `removal*` = "
           "EMULATED third-party liquidity removal; cfg `ALT-*` = alternative parameters or loosened guards (not the candidate).\n")

groups = collections.OrderedDict()
for r in mx:
    key = (r["slice"], r["cfg"], r["side"], r["margin"], r["k"])
    groups.setdefault(key, []).append(r)

out.append("## Margin scenarios\n")
out.append("| slice | cfg | side | margin each | k | trigger (oracle bps of pin) | attempts ok/total | first failure | worst exec cost bps | repaid | seized | keeper reward | borrower surplus | insurance drawn | residual debt | pool reached (bps) |")
out.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
verdict = collections.defaultdict(list)
for key, rows in groups.items():
    att = [r for r in rows if r["liq"]]
    ok = [r for r in att if r["ok"]]
    trig = next((r["oracle"] for r in rows if r["liq"]), None)
    firstfail = next(((r["step"], r["oracle"], r["rev"]) for r in att if not r["ok"]), None)
    worst = max([r["cost"] for r in att] or [0])
    poolmin = min(r["pool"] for r in rows) if rows[0]["side"] == "long" else max(r["pool"] for r in rows)
    clean = bool(att) and not firstfail and sum(r["ins"] for r in att) == 0
    verdict[(key[0], key[1], key[2])].append((key[3] * key[4], clean, bool(att), firstfail))
    out.append("| " + " | ".join([
        key[0], key[1], key[2], f"{key[3]:,}", str(key[4]),
        ("pool floor" if trig is not None and trig < 200 else str(trig)) if trig is not None else "NOT TRIGGERED",
        f"{len(ok)}/{len(att)}",
        (f"step {firstfail[0]} @ {firstfail[1]} bps: {firstfail[2]}" if firstfail else "-"),
        str(worst), money(sum(r["repay"] for r in ok)), money(sum(r["seized"] for r in ok)),
        money(sum(r["reward"] for r in ok)), money(sum(r["surplus"] for r in ok)),
        money(sum(r["ins"] for r in att)), money(sum(r["resid"] for r in att[-1:])), str(poolmin)]) + " |")

if opn:
    out.append("\n## Open failures (position could not be opened)\n")
    out.append("| slice | cfg | side | margin each | requested k | opened | revert |")
    out.append("|---|---|---|---|---|---|---|")
    for o in opn:
        out.append(f"| {o['slice']} | {o['cfg']} | {o['side']} | {o['margin']:,} | {o['k']} | {o['opened']} | {o['rev']} |")

out.append("\n## Liquidation capacity per (slice, cfg, side)\n")
out.append("Per tested size: result of the FIRST liquidation attempt once the position becomes liquidatable on the path (`ok` / `FAIL`), "
           "`-` = never liquidatable on the reachable path (the pool cannot reach the trigger without being emptied: NOT evidence of safety). "
           "`oracle-only` rows use a mocked oracle with the pool untouched: favourable-state evidence, reported but never used for caps.\n")
out.append("| slice | cfg | side | 1k margin | 5k margin | 25k margin | first failure |")
out.append("|---|---|---|---|---|---|---|")
first = collections.OrderedDict()
for key, rows in groups.items():
    sl, cfg, side, margin, k = key
    att = [r for r in rows if r["liq"]]
    res = "-" if not att else ("ok" if att[0]["ok"] else "FAIL")
    allok = bool(att) and all(r["ok"] for r in att)
    d = first.setdefault((sl, cfg, side), {})
    d.setdefault((margin, k), (res, allok, att[0] if att else None, next((r for r in att if not r["ok"]), None)))
cap_inputs = collections.defaultdict(dict)  # (cfg, side) -> slice -> {size: res}
for (sl, cfg, side), d in first.items():
    cells = []
    for m in (1000, 5000, 25000):
        v = d.get((m, 1))
        cells.append(v[0] if v else "n/a")
    ff = next((v[3] for v in d.values() if v[3]), None)
    ffs = f"oracle {ff['oracle']} bps / pool {ff['pool']} bps: {ff['rev']}" if ff else "-"
    out.append(f"| {sl} | {cfg} | {side} | {cells[0]} | {cells[1]} | {cells[2]} | {ffs} |")
    if not sl.startswith("oracle-only") and not sl.startswith("agg"):
        cap_inputs[(cfg, side)][sl] = {m: (d[(m, 1)][0] if (m, 1) in d else "n/a") for m in (1000, 5000, 25000)}

out.append("\n## Candidate caps derived from executed stress scenarios only\n")
out.append("Largest single-position margin size whose first liquidation succeeded in EVERY executed stress slice (pool-follows, lag50, lag90, fixed lags, removal50, accrual) for that config and side; `-`/`FAIL` in any slice disqualifies the size. "
           "`not triggered` means the slice never made the position liquidatable (no evidence), `UNSUPPORTED` means no tested size passed. Aggregate cap = single cap / 2 (safety factor, handoff 00 section 4). The margin-each sizes are 2x notional.\n")
out.append("| cfg | side | slices considered | max margin size passing all | aggregate cap (margin) after /2 | disqualifying slices |")
out.append("|---|---|---|---|---|---|")
for (cfg, side), sls in cap_inputs.items():
    passing = []
    bad = collections.defaultdict(list)
    for m in (1000, 5000, 25000):
        ok_all = True
        for sl, cells in sls.items():
            if cells[m] != "ok":
                ok_all = False
                bad[sl].append(f"{m//1000}k:{cells[m]}")
        if ok_all:
            passing.append(m)
    best = max(passing) if passing else None
    out.append(f"| {cfg} | {side} | {', '.join(sls)} | " + (f"{best:,}" if best else "UNSUPPORTED") + " | " +
               (f"{best//2:,}" if best else "0") + " | " + ("; ".join(f"{k}: {', '.join(v)}" for k, v in bad.items()) or "-") + " |")

if ox:
    out.append("\n## Ordinary lending liquidations (funded liquidator, no swap)\n")
    out.append("USD. `shortfall` = borrowers in shortfall at the step; liquidator budget = sum of repays; net seized excludes the 2.8% protocol share. `bad debt` = residual debt not covered by remaining collateral.\n")
    out.append("| direction | borrow util % | borrowers | step (AVAX bps of pin) | in shortfall | repaid (liquidator budget) | net seized | protocol share | residual debt | bad debt |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    for r in ox:
        if r["short"] == 0 and r["bad"] == 0 and r["repay"] == 0:
            continue
        out.append(f"| {r['dir']} | {r['util']} | {r['n']} | {r['target']} | {r['short']} | {money(r['repay'])} | {money(r['seized'])} | {money(r['proto'])} | {money(r['resid'])} | {money(r['bad'])} |")
    firstbad = {}
    for r in ox:
        if r["bad"] > 0:
            firstbad.setdefault((r["dir"], r["util"], r["n"]), r["target"])
    out.append("\nFirst step with bad debt per (direction, util, borrowers): " + (", ".join(f"{k}: {v} bps" for k, v in firstbad.items()) or "none in the tested range"))

if sg:
    out.append("\n## Swap-guard reconciliation (real `IsolatedMarginSwapModule`, $5k notional)\n")
    out.append("`delta` = oracle price relative to the pool price (bps). Expected/min/actual are token base units; exec/pool/oracle are USD per AVAX x1e8.\n")
    out.append("| guard | direction | oracle vs pool (bps) | oracle | pool | expected out | min out | actual out | exec price | result |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    for p, q in sg:
        kv = dict(x.split("=") for x in p[4:] if "=" in x)
        res = q[1] + ("" if q[2] == "-" else f": {q[2]}")
        out.append(f"| {p[1]} | {p[2]} | {p[3]} | {kv['oracleE8']} | {kv['poolE8']} | {kv['expectedOut']} | {kv['minOut']} | {kv['actualOut']} | {kv['execE8']} | {res} |")

print("\n".join(out))
